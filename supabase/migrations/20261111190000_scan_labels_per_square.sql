-- Snapchess: one row per labelled square, replacing the per-photo scan_labels
-- table from 20261111170000 (that schema was never applied or used).
-- Rows are append-only; the latest row per (board_id, square) is the label.
-- Files live in the private "scan-crops" bucket under
-- "<session_id>/<board_id>/{square}.png | {square}_tight.png | board.png".

-- 1. Drop the old per-photo table (cascade also drops its policies and index) ---

drop table if exists public.scan_labels cascade;

-- 2. Per-square table ------------------------------------------------------------

create table public.scan_labels (
  -- generated by the client so a retried insert is a harmless duplicate
  id                    uuid primary key,
  -- the anonymous user id
  session_id            uuid not null default auth.uid() check (session_id = auth.uid()),
  board_id              uuid not null,
  created_at            timestamptz not null default now(),

  square                text not null check (square ~ '^[a-h][1-8]$'),
  colour                text not null check (colour in ('w', 'b', 'empty')),
  piece                 text check (piece in ('K', 'Q', 'R', 'B', 'N', 'P')),
  source                text not null check (source in ('model_guess_confirmed', 'user_corrected', 'user_manual')),
  is_correction         boolean generated always as (source = 'user_corrected') stored,

  model_guess           text,
  model_version         text,
  model_confidence      real,

  crop_image_path       text,
  tight_crop_path       text,
  full_board_image_path text,
  -- {"corners":[{x,y} x4 in tap order],"rotationSteps90":n,"imageWidth":w,"imageHeight":h}
  corner_points         jsonb,
  camera_side           text,
  crop_geometry         text,
  camera_angle_estimate real,
  board_style_tag       text,

  constraint scan_labels_piece_matches_colour check (
    (colour = 'empty' and piece is null) or (colour <> 'empty' and piece is not null)
  )
);

create index scan_labels_board_square_created_idx
  on public.scan_labels (board_id, square, created_at);

create index scan_labels_is_correction_idx
  on public.scan_labels (is_correction);

-- 3. Row level security: insert and select own rows only -------------------------

alter table public.scan_labels enable row level security;

revoke all on public.scan_labels from anon, authenticated;
grant select, insert on public.scan_labels to authenticated;

create policy "scan_labels insert own"
  on public.scan_labels
  for insert
  to authenticated
  with check (session_id = (select auth.uid()));

create policy "scan_labels select own"
  on public.scan_labels
  for select
  to authenticated
  using (session_id = (select auth.uid()));

-- No update or delete policies: labels are append-only.

-- 4. Storage bucket and policies -------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('scan-crops', 'scan-crops', false, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

drop policy if exists "scan-crops insert own folder" on storage.objects;
create policy "scan-crops insert own folder"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'scan-crops'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "scan-crops select own folder" on storage.objects;
create policy "scan-crops select own folder"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'scan-crops'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

-- No update/delete on files; the app uploads with upsert: false.
